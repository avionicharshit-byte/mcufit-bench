#!/usr/bin/env python3
"""Turn a .tflite file into a 16-byte-aligned C array TFLM can read from flash.

TFLM reads the model in place, so the bytes must be aligned. Embedding via
CMake's EMBED_FILES does not guarantee that, hence this.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HEADER = """// Generated by scripts/gen_model_array.py - do not edit.
// source: {name}
// sha256: {digest}
// bytes:  {size}

#include "model_data.h"

const unsigned int g_{sym}_len = {size};
const char g_{sym}_sha256[] = "{digest}";

alignas(16) const unsigned char g_{sym}[] = {{
"""


def main() -> int:
    if len(sys.argv) not in (3, 4):
        print("usage: gen_model_array.py <model.tflite> <out.cc> [symbol]", file=sys.stderr)
        return 2

    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    sym = sys.argv[3] if len(sys.argv) == 4 else "model"
    blob = src.read_bytes()
    digest = hashlib.sha256(blob).hexdigest()

    lines = [HEADER.format(name=src.name, digest=digest, size=len(blob), sym=sym)]
    for start in range(0, len(blob), 16):
        row = blob[start : start + 16]
        lines.append("  " + "".join(f"0x{b:02x}, " for b in row).rstrip() + "\n")
    lines.append("};\n")

    dst.write_text("".join(lines))
    print(f"{dst}: {len(blob)} bytes, sha256 {digest[:16]}...")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
